import os
from copy import deepcopy

import numpy as np
import sapien
import torch

from mani_skill.agents.base_agent import BaseAgent, Keyframe
from mani_skill.agents.controllers import *
from mani_skill.agents.registration import register_agent
from mani_skill.utils import common, sapien_utils
from mani_skill.utils.structs.actor import Actor
from mani_skill.sensors.camera import CameraConfig


@register_agent()
class BimanualDK1(BaseAgent):
    """Bimanual TRLC-DK1 — two 6-DOF arms with parallel grippers.

    DK1 shares YAM's kinematic skeleton (same link lengths + joint axes; the
    arm joint map is identity, verified by FK), so this agent mirrors
    ``bimanual_yam.py``: same joint ordering, gains (DK1 uses the same DAMIAO
    DM4340/DM4310 motors as YAM), and camera intrinsics. The bimanual URDF is
    generated by ``scripts/build_bimanual_dk1_urdf.py``.
    """

    uid = "bimanual_dk1"

    urdf_path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "..", "assets", "dk1", "bimanual_dk1.urdf",
    )
    urdf_config = dict()

    keyframes = dict(
        home=Keyframe(qpos=np.zeros(16), pose=sapien.Pose()),
    )

    left_arm_joint_names = [
        "left_joint1", "left_joint2", "left_joint3",
        "left_joint4", "left_joint5", "left_joint6",
    ]
    right_arm_joint_names = [
        "right_joint1", "right_joint2", "right_joint3",
        "right_joint4", "right_joint5", "right_joint6",
    ]
    arm_joint_names = left_arm_joint_names + right_arm_joint_names

    left_gripper_joint_names  = ["left_gripper_left",  "left_gripper_right"]
    right_gripper_joint_names = ["right_gripper_left", "right_gripper_right"]
    gripper_joint_names = left_gripper_joint_names + right_gripper_joint_names

    left_ee_link_name  = "left_link6-7"
    right_ee_link_name = "right_link6-7"

    # DK1 motors == YAM motors (DM4340 j1-3, DM4310 j4-6) → reuse YAM gains.
    arm_stiffness   = [40.,  40.,  40.,  20.,  10.,  10.]
    arm_damping     = [2.5,  2.5,  2.5,  0.5,  1.0,  1.0]
    arm_force_limit = [28.,  28.,  28.,  10.,  10.,  10.]

    gripper_stiffness   = 2e3
    gripper_damping     = 40.
    gripper_force_limit = 40.  # YAM parity (grasp verified at parity)

    # DK1 prismatic gripper travel: URDF range [-0.045, 0.001]. NB the DK1
    # gripper convention is INVERTED vs YAM: it is CLOSED at the lower limit
    # (-0.045, fingers together) and OPEN at the upper limit (+0.001, apart).
    # The controller maps action -1 → lower (closed), +1 → upper (open); the
    # inversion is handled in dk1_action_adapter / dk1_state_adapter (out=2g-1).
    gripper_lower = -0.045
    gripper_upper = 0.001

    gripper_static_friction  = 3.0  # YAM parity
    gripper_dynamic_friction = 2.5

    # 360×640, matching MolmoAct2 YAM training images.
    cam_width  = 640
    cam_height = 360
    # Reuse YAM intrinsics so the policy sees in-distribution images:
    # top = RealSense D435i (69.4°), wrists = D405 (87°).
    top_cam_hfov_deg   = 69.4
    wrist_cam_hfov_deg = 87.0

    @staticmethod
    def _intrinsic_from_hfov(width: int, height: int, hfov_deg: float) -> np.ndarray:
        fx = (width / 2.0) / np.tan(np.deg2rad(hfov_deg) / 2.0)
        return np.array(
            [[fx, 0.0, width / 2.0],
             [0.0, fx, height / 2.0],
             [0.0, 0.0, 1.0]],
            dtype=np.float32,
        )

    @property
    def _sensor_configs(self):
        w, h = self.cam_width, self.cam_height
        common_cfg = dict(width=w, height=h, near=0.01, far=100)
        top_K   = self._intrinsic_from_hfov(w, h, self.top_cam_hfov_deg)
        wrist_K = self._intrinsic_from_hfov(w, h, self.wrist_cam_hfov_deg)
        # top_cam mounts on bimanual_base (frame matches YAM), so its pose is
        # copied directly from bimanual_yam.py. The wrist-cam poses are YAM's
        # link_6-frame camera re-expressed in DK1's link6-7 frame via the
        # constant wrist-frame difference (C_dk1 = T_dk1_link67(0)^-1 @
        # T_yam_link6(0) @ C_yam), so the wrist view matches YAM's despite the
        # different link frame convention. See scripts/wrist_cam_pose.py.
        wrist_cam_pose = sapien.Pose(
            p=[0.076428, 0.0, 0.094029],
            q=[0.965926, 0.0, 0.258819, 0.0],
        )
        return [
            CameraConfig(
                uid="top_cam",
                pose=sapien.Pose(p=[0.15, 0, 0.8], q=[0.7660444431189782, 0, 0.6427876096865391, 0]),
                intrinsic=top_K,
                mount=self.robot.links_map["bimanual_base"],
                **common_cfg,
            ),
            CameraConfig(
                uid="left_cam",
                pose=wrist_cam_pose,
                intrinsic=wrist_K,
                mount=self.robot.links_map[self.left_ee_link_name],
                **common_cfg,
            ),
            CameraConfig(
                uid="right_cam",
                pose=wrist_cam_pose,
                intrinsic=wrist_K,
                mount=self.robot.links_map[self.right_ee_link_name],
                **common_cfg,
            ),
        ]

    @property
    def _controller_configs(self):
        def arm_cfg(joint_names):
            return PDJointPosControllerConfig(
                joint_names, lower=None, upper=None,
                stiffness=self.arm_stiffness, damping=self.arm_damping,
                force_limit=self.arm_force_limit, normalize_action=False,
            )

        def gripper_cfg(joint_names, mimic_follower, mimic_leader):
            return PDJointPosMimicControllerConfig(
                joint_names, lower=self.gripper_lower, upper=self.gripper_upper,
                stiffness=self.gripper_stiffness, damping=self.gripper_damping,
                force_limit=self.gripper_force_limit,
                mimic={mimic_follower: {"joint": mimic_leader}},
            )

        return deepcopy(dict(
            pd_joint_pos=dict(
                left_arm=arm_cfg(self.left_arm_joint_names),
                left_gripper=gripper_cfg(self.left_gripper_joint_names, "left_gripper_right", "left_gripper_left"),
                right_arm=arm_cfg(self.right_arm_joint_names),
                right_gripper=gripper_cfg(self.right_gripper_joint_names, "right_gripper_right", "right_gripper_left"),
            ),
        ))

    def _after_init(self):
        self.left_finger1_link  = sapien_utils.get_obj_by_name(self.robot.get_links(), "left_finger_left")
        self.left_finger2_link  = sapien_utils.get_obj_by_name(self.robot.get_links(), "left_finger_right")
        self.left_tcp           = sapien_utils.get_obj_by_name(self.robot.get_links(), self.left_ee_link_name)
        self.right_finger1_link = sapien_utils.get_obj_by_name(self.robot.get_links(), "right_finger_left")
        self.right_finger2_link = sapien_utils.get_obj_by_name(self.robot.get_links(), "right_finger_right")
        self.right_tcp          = sapien_utils.get_obj_by_name(self.robot.get_links(), self.right_ee_link_name)
        self._set_gripper_friction(self.gripper_static_friction, self.gripper_dynamic_friction)

        # DIAGNOSTIC (not a real-world fix): DK1 renders near-black (~RGB 34,34,34)
        # while the MolmoAct2-YAM policy was trained on YAM's medium-gray arms
        # (~RGB 91,89,89). Setting DK1_RECOLOR=1 overrides DK1's render material
        # to YAM's gray so we can test whether the appearance gap (not geometry)
        # is what limits closed-loop reliability. A real black DK1 can't be
        # repainted to match training, so a positive result means "out-of-the-box
        # needs fine-tuning / domain adaptation", NOT a deployable fix.
        recolor = os.environ.get("DK1_RECOLOR", "")
        if recolor and recolor != "0":
            # Optional "R,G,B" override; default = YAM arm gray sampled from sim.
            try:
                rgb = [float(x) for x in recolor.split(",")] if "," in recolor else [0.357, 0.349, 0.349]
            except ValueError:
                rgb = [0.357, 0.349, 0.349]
            self._recolor_arms(rgb + [1.0])

    def _recolor_arms(self, rgba):
        """Override every render shape's base color (GLB meshes ship embedded
        materials, so this must be a runtime RenderMaterial override, not a URDF
        <color>). Walks link entity -> RenderBodyComponent -> render_shapes ->
        parts -> material. Idempotent; safe if a link has no render body."""
        import sapien.render as sr
        n_parts = 0
        for link in self.robot.get_links():
            for link_comp in link._objs:  # PhysxArticulationLinkComponent
                entity = link_comp.entity
                rb = entity.find_component_by_type(sr.RenderBodyComponent)
                if rb is None:
                    continue
                for shape in rb.render_shapes:
                    parts = getattr(shape, "parts", None) or [shape]
                    for part in parts:
                        mat = getattr(part, "material", None)
                        if mat is None:
                            continue
                        mat.set_base_color(rgba)
                        try:
                            mat.set_metallic(0.0)
                            mat.set_roughness(0.7)
                        except Exception:
                            pass
                        n_parts += 1
        print(f"[bimanual_dk1] recolored {n_parts} render parts -> base_color={rgba}")

    def _set_gripper_friction(self, static_friction: float, dynamic_friction: float):
        import sapien.physx as physx
        for link in [self.left_finger1_link, self.left_finger2_link,
                     self.right_finger1_link, self.right_finger2_link]:
            for body in link._bodies:
                for cs in body.get_collision_shapes():
                    cs.physical_material = physx.PhysxMaterial(
                        static_friction=static_friction,
                        dynamic_friction=dynamic_friction,
                        restitution=0.0,
                    )

    def is_grasping(self, object: Actor, arm: str = "left", min_force=0.5, max_angle=85):
        if arm == "left":
            f1, f2 = self.left_finger1_link, self.left_finger2_link
        else:
            f1, f2 = self.right_finger1_link, self.right_finger2_link
        lf = self.scene.get_pairwise_contact_forces(f1, object)
        rf = self.scene.get_pairwise_contact_forces(f2, object)
        ld = f1.pose.to_transformation_matrix()[..., :3, 1]
        rd = -f2.pose.to_transformation_matrix()[..., :3, 1]
        lflag = (torch.linalg.norm(lf, axis=1) >= min_force) & (torch.rad2deg(common.compute_angle_between(ld, lf)) <= max_angle)
        rflag = (torch.linalg.norm(rf, axis=1) >= min_force) & (torch.rad2deg(common.compute_angle_between(rd, rf)) <= max_angle)
        return lflag & rflag

    def is_static(self, threshold: float = 0.2):
        qvel = self.robot.get_qvel()[..., :-4]
        return torch.max(torch.abs(qvel), 1)[0] <= threshold

    @property
    def left_tcp_pos(self):
        return self.left_tcp.pose.p

    @property
    def right_tcp_pos(self):
        return self.right_tcp.pose.p

    @property
    def left_tcp_pose(self):
        return self.left_tcp.pose

    @property
    def right_tcp_pose(self):
        return self.right_tcp.pose
